#!/usr/bin/env python3
"""Migrate the SQLite Arduino library to a new upstream release.

Source of truth: https://github.com/sqlite/sqlite (cloned into original/sqlite).

What it does:
  1. Optionally checks out an upstream tag (detached HEAD), e.g. version-3.54.1.
  2. Generates the amalgamation (sqlite3.c, sqlite3.h, sqlite3ext.h) with
     ./configure and make if it is missing or --regenerate is given.
  3. Writes src/sqlite3.c as: the Arduino config header (src/sqlite3_config.h)
     followed by the unmodified upstream amalgamation.
  4. Copies sqlite3.h and sqlite3ext.h into src/.
  5. Updates version= in library.properties to the upstream version.
  6. Verifies the result: versions agree and the config header is first.

Only the Python standard library is used.

Examples:
  python3 tools/migrate_upstream.py --tag version-3.54.1
  python3 tools/migrate_upstream.py --regenerate
  python3 tools/migrate_upstream.py --check        # verify only, change nothing
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

LIB_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_UPSTREAM = LIB_ROOT / "original" / "sqlite"
CONFIG_HEADER = "sqlite3_config.h"
VERSION_RE = re.compile(r'#define\s+SQLITE_VERSION\s+"([0-9.]+)"')
GENERATED_FILES = ("sqlite3.c", "sqlite3.h", "sqlite3ext.h")


def run(cmd: list[str], cwd: Path) -> str:
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"error: {' '.join(cmd)} failed in {cwd}:\n{result.stderr or result.stdout}")
    return result.stdout.strip()


def checkout_tag(upstream: Path, tag: str) -> None:
    run(["git", "rev-parse", "--verify", f"refs/tags/{tag}"], upstream)
    run(["git", "checkout", "--detach", "--quiet", tag], upstream)
    print(f"upstream: checked out {tag}")


def generate_amalgamation(upstream: Path) -> None:
    print("upstream: running ./configure and make sqlite3.c sqlite3.h sqlite3ext.h")
    run(["./configure"], upstream)
    run(["make", "sqlite3.c", "sqlite3.h", "sqlite3ext.h"], upstream)


def upstream_version(header: Path) -> str:
    match = VERSION_RE.search(header.read_text(encoding="utf-8", errors="replace"))
    if not match:
        sys.exit(f"error: no SQLITE_VERSION in {header}")
    return match.group(1)


def write_library(upstream: Path, version: str) -> None:
    src = LIB_ROOT / "src"
    src.mkdir(exist_ok=True)
    config = src / CONFIG_HEADER
    if not config.exists():
        sys.exit(f"error: missing {config}; it must exist before migrating")

    amalgamation = (upstream / "sqlite3.c").read_text(encoding="utf-8", errors="replace")
    # Arduino cores include <assert.h> before our config header. The upstream
    # include would re-enable assert(); sqlite3_config.h defines assert() as a
    # no-op, so drop the include. (Upstream asserts need SQLITE_DEBUG helpers.)
    amalgamation, n_assert = re.subn(
        r"^#include <assert\.h>.*$",
        "/* #include <assert.h>: removed by tools/migrate_upstream.py (see sqlite3_config.h) */",
        amalgamation, flags=re.M)
    print(f"patch: removed {n_assert} live #include <assert.h>")
    banner = (
        "/*\n"
        f" * GENERATED by tools/migrate_upstream.py from SQLite {version}.\n"
        " * Do not edit: change src/sqlite3_config.h or the migration script.\n"
        " * Upstream: https://github.com/sqlite/sqlite\n"
        " */\n"
    )
    (src / "sqlite3.c").write_text(
        banner + f'#include "{CONFIG_HEADER}"\n' + amalgamation, encoding="utf-8"
    )
    for name in ("sqlite3.h", "sqlite3ext.h"):
        shutil.copyfile(upstream / name, src / name)
    print(f"library: wrote src/sqlite3.c, src/sqlite3.h, src/sqlite3ext.h ({version})")


def update_properties(version: str) -> None:
    props = LIB_ROOT / "library.properties"
    text = props.read_text(encoding="utf-8")
    new_text, count = re.subn(r"^version=.*$", f"version={version}", text, flags=re.M)
    if count == 0:
        new_text = text.rstrip("\n") + f"\nversion={version}\n"
    props.write_text(new_text, encoding="utf-8")
    print(f"library.properties: version={version}")


def verify(version: str) -> None:
    src = LIB_ROOT / "src"
    missing = [n for n in ("sqlite3.c", "sqlite3.h", "sqlite3ext.h", CONFIG_HEADER)
               if not (src / n).exists()]
    if missing:
        sys.exit(f"verify failed: missing {', '.join(missing)}")

    header_version = upstream_version(src / "sqlite3.h")
    if header_version != version:
        sys.exit(f"verify failed: src/sqlite3.h is {header_version}, expected {version}")

    first_line = next(
        line for line in (src / "sqlite3.c").read_text(encoding="utf-8").splitlines()
        if line.startswith("#include")
    )
    if f'"{CONFIG_HEADER}"' not in first_line:
        sys.exit("verify failed: config header is not the first include in src/sqlite3.c")
    print(f"verify: OK (SQLite {version}, config header first)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--upstream", type=Path, default=DEFAULT_UPSTREAM,
                        help="path to the sqlite/sqlite checkout (default: original/sqlite)")
    parser.add_argument("--tag", help="upstream tag to check out, e.g. version-3.54.1")
    parser.add_argument("--regenerate", action="store_true",
                        help="regenerate the amalgamation even if it already exists")
    parser.add_argument("--check", action="store_true",
                        help="only verify the current src/ tree; change nothing")
    args = parser.parse_args()

    upstream = args.upstream.resolve()
    if not (upstream / "configure").exists():
        sys.exit(f"error: {upstream} is not an sqlite source tree (clone https://github.com/sqlite/sqlite)")

    if args.check:
        verify(upstream_version(LIB_ROOT / "src" / "sqlite3.h"))
        return

    if args.tag:
        checkout_tag(upstream, args.tag)

    if args.regenerate or not (upstream / "sqlite3.c").exists():
        generate_amalgamation(upstream)

    version = upstream_version(upstream / "sqlite3.h")
    write_library(upstream, version)
    update_properties(version)
    verify(version)


if __name__ == "__main__":
    main()
